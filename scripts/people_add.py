def main():
    p = 'public/data/bible-people.json'
    d = json.load(open(p))
    people = [x for x in d['people'] if x['id'] not in {a[0] for a in ADD}]
    themes = set(d['themes'])
    for (pid, th, en, role, after, era, refs, ths, lesson) in ADD:
        bad = [t for t in ths if t not in themes]
        assert not bad, (pid, bad)
        idx = next(i for i, x in enumerate(people) if x['id'] == after)
        people.insert(idx + 1, {'th': th, 'en': en, 'role': role, 'era': era, 'id': pid, 'order': 0,
                                'refs': refs, 'themes': ths, 'lesson': lesson, 'review_status': 'draft'})
    for i, x in enumerate(people, 1):
        x['order'] = i
    d['people'] = people
    d['title'] = d['title'].replace('100', str(len(people)))
    json.dump(d, open(p, 'w'), ensure_ascii=False, indent=1)
    print(len(people), 'people')


if __name__ == '__main__':
    main()
