// ท่องจำคัมภีร์: แถบเล็ก 3 แถบบนหัวแอป · ค้นหาข้อพระคัมภีร์จากประโยคยาว → แท็กลบ/เพิ่มได้ → เนื้อหาด้านล่าง → เก็บเข้าหมวด
import { chromium } from 'playwright'
const URL = process.env.URL || 'http://localhost:4173/'
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' })
let fail = 0; const check = (ok, m) => { console.log((ok ? 'PASS ' : 'FAIL ') + m); if (!ok) fail++ }
const p = await (await b.newContext({ viewport: { width: 390, height: 844 } })).newPage()
const errs = []; p.on('pageerror', (e) => errs.push(e.message))
await p.goto(URL + '#/notebook/1'); await p.waitForSelector('#nb-catsel')
const tabs = await p.locator('.sm-tab').allTextContents()
check(tabs.length === 3 && tabs[0].includes('ค้นหาข้อพระคัมภีร์'), '3 small tabs in the top bar, tab 1 = ค้นหาข้อพระคัมภีร์: ' + tabs.join(' | '))
const box = await p.locator('.sm-tabs').boundingBox(); check(box && box.y < 70 && box.width > 150, 'tabs sit in the header bar (y=' + Math.round(box?.y) + ', w=' + Math.round(box?.width) + ')')
await p.click('.sm-tab >> text=ค้นหาข้อพระคัมภีร์'); await p.waitForSelector('#bs-q')
await p.fill('#bs-q', 'การรักษาผู้ป่วยที่หมดกำลังใจ ผู้ที่ต้องการความเข้มแข็งในจิตใจ ผู้ต้องการรักษาให้หายขาด และเสริมกำลังเรี่ยวแรง')
await p.getByRole('button', { name: '🔎 ค้นหา', exact: true }).click(); await p.waitForSelector('.bs__tag', { timeout: 60000 })
const n0 = await p.locator('.bs__tag').count(); check(n0 >= 5, 'found related verses as tags (' + n0 + ')')
const tagText = await p.locator('.bs__tag span').allTextContents(); console.log('   tags:', tagText.join(', '))
check(tagText.some((t) => /ยากอบ 5|สดุดี 103|อิสยาห์ 40|อิสยาห์ 53/.test(t)), 'includes well-known healing/strength verses')
await p.waitForFunction(() => document.querySelectorAll('.bs__card .bs__text').length >= 5, null, { timeout: 30000 })
check(await p.locator('.bs__card').count() === n0, 'a content card below for every tag')
const first = tagText[0]
await p.click(`[aria-label="ลบ ${first}"]`)
check(await p.locator('.bs__tag').count() === n0 - 1 && await p.locator('.bs__card').count() === n0 - 1, 'removing a tag removes its content card')
await p.fill('#bs-add', 'สดุดี 23:1–3'); await p.keyboard.press('Enter')
await p.waitForFunction(() => [...document.querySelectorAll('.bs__tag span')].some((e) => e.textContent === 'สดุดี 23:1–3'))
check(await p.locator('.bs__tag').count() === n0, 'typing a ref adds a tag')
await p.waitForFunction(() => [...document.querySelectorAll('.bs__card')].some((c) => c.textContent.includes('สดุดี 23:1–3') && c.querySelectorAll('sup').length === 3))
check(true, 'its 3 verses appear numbered below')
const card = p.locator('.bs__card', { hasText: 'สดุดี 23:1–3' }); await card.getByRole('button', { name: '💾 เก็บข้อนี้' }).click()
check((await card.textContent()).includes('เก็บแล้ว'), 'save to category (ไม่มีหมวด)')
const stored = await p.evaluate(() => JSON.parse(localStorage.getItem('khatha.notebook1.v1') || '[]'))
check(stored.length === 1 && stored[0].title === 'สดุดี 23:1–3' && stored[0].text.split('\n').length === 3, 'stored in notebook1 as 3 numbered verse lines')
await p.click('.sm-tab >> text=หมวด'); check((await p.locator('.sm-cat').allTextContents()).some((t) => t.includes('ไม่มีหมวด') && t.includes('1 ข้อ')), 'appears under ไม่มีหมวด in the category tab')
check(errs.length === 0, 'no JS errors ' + errs.join(';'))
await b.close(); console.log(fail ? 'FAILED' : 'ALL PASSED'); process.exit(fail ? 1 : 0)
