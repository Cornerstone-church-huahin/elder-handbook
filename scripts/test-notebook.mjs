// สมุดคำอธิษฐาน: ค้นหา → การ์ดที่ตรงกางออก · เพิ่ม (เต็มจอ) → บันทึก → พับเป็นการ์ด · แก้ไข · ลบ · เก็บหลังรีโหลด
import { chromium } from 'playwright'
const URL = process.env.URL || 'http://localhost:4173/'
const SHOT = process.env.SHOT
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' })
let fail = 0; const check = (ok, m) => { console.log((ok ? 'PASS ' : 'FAIL ') + m); if (!ok) fail++ }
const p = await (await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 })).newPage()
const errs = []; p.on('pageerror', (e) => errs.push(e.message))
await p.goto(URL + '#/prayer'); await p.waitForSelector('.nb-card')
check(await p.locator('.nb-card').count() === 5, '5 starter prayers as small cards')
check(await p.locator('text=สร้างคำอธิษฐาน').count() === 0, 'no "create prayer" button')
const h = await p.locator('#nb-q').evaluate((e) => e.getBoundingClientRect().height)
check(h < 50, `search box is one line (h=${h})`)
if (SHOT) await p.screenshot({ path: SHOT + '/nb-list.png' })

await p.fill('#nb-q', 'อาหาร'); await p.waitForTimeout(400)
check(await p.locator('.nb-card').count() < 5 && await p.locator('.nb-card--open').count() === 1 && (await p.locator('.nb-card').first().textContent()).includes('กระยาหาร'), 'search: matching cards only, best one first and expanded')
check(await p.locator('.nb-card--open .nb-tabs button').count() === 4, 'expanded card has 4 tabs')
await p.waitForSelector('.nb-card--open .nb-verse'); check(await p.locator('.nb-card--open .nb-verse').count() === 2, 'verses tab shows 2 verses')
check((await p.locator('.nb-card--open .nb-verse').first().getAttribute('href')).includes('bible.com/th/bible/275/JHN.6.11.TH1971'), 'verse links to TH1971 on bible.com')
await p.click('.nb-card--open .nb-tabs >> text=เรื่องราว'); check((await p.textContent('.nb-card--open .nb-panel')).includes('ห้าพันคน'), 'story tab')
await p.click('.nb-card--open .nb-tabs >> text=อธิษฐาน'); check((await p.textContent('.nb-card--open .nb-panel')).includes('ชำระอาหาร'), 'prayer tab shows full prayer')
await p.click('.nb-card--open .nb-tabs >> text=บันทึก'); await p.fill('.nb-card--open .nb-notes textarea', 'ใช้ในงานเลี้ยงวันเกิด'); await p.click('.nb-card--open .nb-notes >> text=บันทึก')
check((await p.textContent('.nb-card--open')).includes('บันทึกแล้ว'), 'notes tab saves')
if (SHOT) await p.screenshot({ path: SHOT + '/nb-search.png' })

await p.fill('#nb-q', ''); await p.click('.nb-add')
check(await p.locator('.nb-editor').count() === 1, 'add opens editor')
const eh = await p.locator('.nb-editor').evaluate((e) => e.getBoundingClientRect().height)
check(eh > 600, `editor fills the screen (h=${eh})`)
await p.fill('#nb-title', 'อธิษฐานเผื่อผู้ป่วยก่อนผ่าตัด'); await p.fill('#nb-cat', 'เจ็บป่วย'); await p.fill('#nb-ref1', 'โยชูวา 1:9'); await p.fill('#nb-ref2', 'อิสยาห์ 41:10'); await p.fill('#nb-story', 'โยชูวาต้องนำประชาชนข้ามแม่น้ำจอร์แดน')
await p.fill('#nb-text', 'ข้าแต่พระบิดาเจ้า ขอทรงอยู่กับพี่น้องในห้องผ่าตัด\n\nในพระนามพระเยซูคริสต์ อาเมน')
if (SHOT) await p.screenshot({ path: SHOT + '/nb-editor.png' })
await p.click('text=💾 บันทึก'); await p.waitForTimeout(300)
check(await p.locator('.nb-editor').count() === 0 && await p.locator('.nb-card').count() === 6 && await p.locator('.nb-card--open').count() === 0, 'saved → collapses into small card')
await p.reload(); await p.waitForSelector('.nb-card')
check(await p.locator('.nb-card').count() === 6, 'kept after reload')
await p.fill('#nb-q', 'ก่อนผ่าตัด'); await p.waitForTimeout(300)
const tags = await p.locator('.nb-card--open .nb-tags button').allTextContents()
check(tags.length >= 4 && tags.length <= 10 && tags.includes('#เจ็บป่วย') && tags.includes('#ผ่าตัด'), 'auto tags created on save: ' + tags.join(' '))
await p.fill('#nb-q', 'หนี้'); await p.waitForTimeout(300)
check((await p.locator('.nb-card').first().textContent()).includes('การเงิน'), 'tag search: "หนี้" finds finance prayer')
await p.locator('.nb-card--open .nb-tags button').first().click(); await p.waitForTimeout(200)
check((await p.inputValue('#nb-q')).length > 0, 'tapping a tag searches it')
await p.fill('#nb-q', 'ผ่าตัด'); await p.waitForTimeout(300)
check((await p.locator('.nb-card').first().textContent()).includes('ก่อนผ่าตัด') && await p.locator('.nb-card--open .nb-verse').count() === 2, 'search finds new prayer, shows its 2 verses')
await p.waitForFunction(() => document.querySelector('.nb-card--open .nb-verse')?.textContent.includes('จงเข้มแข็ง'))
check((await p.locator('.nb-card--open .nb-verse').nth(1).textContent()).includes('อย่ากลัวเลย'), 'both verse texts from TH1971')
await p.click('.nb-card--open .nb-card__more'); await p.click('.nb-menu >> text=แก้ไข'); await p.fill('#nb-title', 'ก่อนผ่าตัด (แก้แล้ว)'); await p.click('text=💾 บันทึก'); await p.waitForTimeout(200)
check((await p.textContent('.nb-list')).includes('ก่อนผ่าตัด (แก้แล้ว)'), 'edit works')
await p.fill('#nb-q', 'แก้แล้ว'); await p.waitForTimeout(300)
await p.click('.nb-card--open .nb-card__more'); await p.click('.nb-menu__danger'); await p.click('.duty__btns--warn .btn--danger'); await p.waitForTimeout(200)
await p.fill('#nb-q', ''); await p.waitForTimeout(200)
check(await p.locator('.nb-card').count() === 5, 'delete works')
await p.fill('#nb-q', 'ถวาย'); await p.waitForTimeout(1200); await p.click('.nb-card--open .nb-card__more'); await p.click('.nb-menu__danger'); await p.click('.duty__btns--warn .btn--danger')
await p.fill('#nb-q', ''); await p.click('text=↺ นำคำอธิษฐานตั้งต้นที่ลบไปกลับมา'); await p.waitForTimeout(300)
check(await p.locator('.nb-card').count() === 5, 'restore deleted starter prayer')
await p.goto(URL + '#/search?q=' + encodeURIComponent('ก่อนทานข้าว')); await p.waitForTimeout(500)
check((await p.locator('.result .result__title').first().textContent()).includes('กระยาหาร'), 'global search finds notebook prayer')
await p.click('.result >> nth=0'); await p.waitForSelector('.nb-card--open')
check(true, 'search result opens card in notebook')
check(errs.length === 0, 'no JS errors ' + errs.join(';'))
await b.close(); console.log(fail ? `${fail} FAILED` : 'ALL PASSED'); process.exit(fail ? 1 : 0)
