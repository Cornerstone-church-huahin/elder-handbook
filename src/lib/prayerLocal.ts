const URGENT = /ฆ่าตัวตาย|อยากตาย|ไม่อยากมีชีวิต|ทำร้ายตัวเอง|กินยาเกิน|ทุบตี|ตบตี|ทำร้ายร่างกาย|ล่วงละเมิด|ข่มขืน|หมดสติ|หายใจไม่ออก|เจ็บหน้าอก/

export function buildLocalPrayer(request: string, people: PeopleDoc | null, lib: PrayerLibrary | null = null): PrayerSet {
  const text = request.replace(/\s+/g, ' ').trim()
  const themes = people ? themesInText(people, text) : []
  const key = RULES.find(([re]) => re.test(text))?.[1] ?? ORDER.find(([, ts]) => ts.some((t) => themes.includes(t)))?.[0] ?? 'general'
  const t = T[key]
  const A = t.anchor
  const le = key === 'offering' || key === 'meal' || key === 'finance' ? matchLibrary(lib, key === 'finance' ? 'การเงิน' : text) : null
  const libVersions = le?.id === key ? le.versions : []
  const appPrayer = `ข้าแต่พระบิดาเจ้า ข้าพระองค์ทั้งหลายขอบพระคุณที่ทรงรัก (ชื่อ) และทรงทราบทุกเรื่องที่กำลังเผชิญ ${t.ask} ข้าพระองค์ทั้งหลายขอมอบ (ชื่อ) ไว้ในพระหัตถ์ของพระองค์ ในพระนามพระเยซูคริสต์ อาเมน`
  const appSelf = t.selfPrayer ?? `ข้าแต่พระบิดาเจ้า ข้าพระองค์ขอบพระคุณที่ทรงรู้จักข้าพระองค์และเรื่องที่ข้าพระองค์เผชิญอยู่ ${t.selfAsk} ในพระนามพระเยซูคริสต์ อาเมน`
  const occasion = key === 'offering' || key === 'meal'
  // พิธี (ถวาย/อาหาร): คำอธิษฐานนำ = ต้นฉบับของคริสตจักร · การเงิน: คำอธิษฐานเพื่อตนเอง = ต้นฉบับของคริสตจักร
  const intercedeList = occasion && libVersions.length ? libVersions : [{ label: 'แบบสั้น', text: appPrayer }]
  const selfList = key === 'finance' && libVersions.length ? [...libVersions, { label: 'แบบสั้น', text: appSelf }] : [{ label: 'แบบสั้น', text: appSelf }]
  const shortTopic = text.length > 60 ? text.slice(0, 60) + '…' : text

  return {
    title: t.title,
    keys: [...t.keys],
    scriptures: [{ ref: A.ref, gist: A.gist, person: A.person }, ...t.more],
    people: [
      { id: A.person, story: A.story, bridge: A.compare },
    ].filter((p) => !people || people.people.some((x) => x.id === p.id)),
    intercede: {
      situation: occasion ? (le?.invite && le.id === key ? le.invite.replace(/\n\n/g, ' ') : t.situation ?? '') : `เรารู้ว่า (ชื่อ) กำลังเผชิญเรื่อง “${shortTopic}” พระเจ้าทรงเห็นและทรงเข้าใจทุกความรู้สึก ให้เรานำเรื่องนี้มาไว้ต่อพระองค์ด้วยกัน`,
      before_scripture: A.explain,
      before_person: A.compare,
      prayer: intercedeList[0].text,
      after: t.after,
      breath: t.breath,
    },
    self: {
      before: t.selfNote,
      prayer: selfList[0].text,
      breath: t.breath,
    },
    followup: t.followup,
    occasion,
    versions: { intercede: intercedeList.length > 1 ? intercedeList : undefined, self: selfList.length > 1 ? selfList : undefined },
    safety: URGENT.test(text)
      ? { level: 'urgent', note: 'เรื่องนี้อาจเกี่ยวกับความปลอดภัยของชีวิต ช่วยเหลือทันทีก่อน: เหตุฉุกเฉิน 1669 · สายด่วนสุขภาพจิต 1323 · ศูนย์ช่วยเหลือสังคม 1300 · ตำรวจ 191 และอย่าปล่อยให้อยู่ลำพัง' }
      : { level: 'none', note: '' },
  }
}
