const GROUP = ['ถวายทรัพย์', 'อาหาร', 'การนมัสการ', 'ผู้นำอธิษฐาน']

export function autoCheer(p: { title: string; category: string; refs: string[]; story: string; text: string; notes?: string }): string {
  const tags = autoTags({ ...p, notes: '' }, 12)
  const hay = `${p.title} ${p.category}`
  const group = GROUP.some((g) => tags.slice(0, 3).includes(g)) || /ถวาย|อาหาร|กระยาหาร|นมัสการ|คริสตจักร/.test(hay)
  const you = group ? 'ทุกคน' : 'คุณ'
  const out: string[] = []
  if (/ตื่นนอน|ยามเช้า|วันใหม่/.test(hay)) out.push(`ขอให้วันนี้เป็นวันที่ดีสำหรับ${you} ขอพระเจ้าทรงนำทุกย่างก้าว และให้${you}เป็นพรแก่ทุกคนที่พบเจอ`)
  else if (/ก่อนนอน|นอนหลับ|ค่ำคืน|กลางคืน/.test(hay)) out.push(`ขอให้คืนนี้${you}หลับสนิทในความสงบ พระเจ้าผู้ทรงดูแล${you}ไม่เคยหลับ พรุ่งนี้ตื่นขึ้นมาพร้อมกำลังใหม่นะ`)
  else if (/ถวาย/.test(hay)) out.push('ขอพระเจ้าทรงใช้ของถวายนี้เพื่อพระราชกิจของพระองค์ และทรงอวยพรชีวิตของผู้ถวายทุกคนที่ให้ด้วยใจยินดี')
  else if (/อาหาร|กระยาหาร/.test(hay)) out.push('ขอพระเจ้าทรงอวยพรอาหารและทุกคนรอบโต๊ะนี้ ให้เรามีสุขภาพดีและมีใจขอบพระคุณทุกวัน')
  for (const [keys, line] of LINES) {
    if (out.length >= 2) break
    if (keys.some((k) => tags.includes(k))) out.push(group ? line.replaceAll('คุณ', 'ทุกคน') : line)
  }
  const ref = p.refs.map((r) => parseRef(r)?.label).find(Boolean)
  if (ref) out.push(`ขอให้พระคำใน${ref} อยู่ในใจของ${you}และหนุนใจ${you}ในวันนี้`)
  out.push(group ? 'ขอพระเจ้าทรงอวยพรทุกคน และสถิตอยู่กับพวกเราเสมอ อาเมน' : 'ขอพระเจ้าทรงอวยพรและอยู่กับคุณเสมอนะ พวกเราจะอธิษฐานเผื่อคุณต่อไป')
  return out.join('\n\n')
}
