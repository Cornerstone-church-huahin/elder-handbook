export const ALL_OCCASIONS = [...RITES, ...DAYS]
export const findOccasion = (id: string) => ALL_OCCASIONS.find((o) => o.id === id)

/** วันสำคัญที่กำลังจะถึง (ปีนี้และปีหน้า) เรียงตามวันที่ */
export function upcomingDates(from = new Date(), limit = 12): { o: Occasion; label: string; date: Date }[] {
  const start = new Date(from.getFullYear(), from.getMonth(), from.getDate())
  const out: { o: Occasion; label: string; date: Date }[] = []
  for (const y of [from.getFullYear(), from.getFullYear() + 1]) {
    for (const o of DAYS) for (const [label, date] of o.dates?.(y) ?? []) if (date >= start) out.push({ o, label, date })
  }
  const seen = new Set<string>()
  return out
    .sort((a, b) => a.date.getTime() - b.date.getTime())
    .filter((x) => { const k = `${x.label}${x.date.toDateString()}`; if (seen.has(k)) return false; seen.add(k); return true })
    .slice(0, limit)
}
