/** วันอีสเตอร์ (ปฏิทินเกรกอเรียน · วิธีคำนวณแบบ Meeus/Jones/Butcher) */
export function easter(y: number): Date {
  const a = y % 19
  const b = Math.floor(y / 100)
  const c = y % 100
  const d = Math.floor(b / 4)
  const e = b % 4
  const f = Math.floor((b + 8) / 25)
  const g = Math.floor((b - f + 1) / 3)
  const h = (19 * a + b - d - g + 15) % 30
  const i = Math.floor(c / 4)
  const k = c % 4
  const l = (32 + 2 * e + 2 * i - h - k) % 7
  const m = Math.floor((a + 11 * h + 22 * l) / 451)
  const month = Math.floor((h + l - 7 * m + 114) / 31)
  const day = ((h + l - 7 * m + 114) % 31) + 1
  return new Date(y, month - 1, day)
}
const add = (d: Date, n: number) => new Date(d.getFullYear(), d.getMonth(), d.getDate() + n)
/** วันอาทิตย์แรกของเทศกาลรอคอย = อาทิตย์ที่ 4 ก่อนวันคริสต์มาส */
export function advent1(y: number): Date {
  const xmas = new Date(y, 11, 25)
  const back = xmas.getDay() === 0 ? 7 : xmas.getDay()
  return add(xmas, -back - 21)
}

