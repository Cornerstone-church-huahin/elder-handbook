const parsed = POPULAR_REFS.map((r) => parseRef(r)).filter((x): x is NonNullable<ReturnType<typeof parseRef>> => !!x && x.verses.length > 0)

/** อันดับความนิยมของข้ออ้างอิง (0 = นิยมที่สุด) · -1 = ไม่อยู่ในรายการ · นับว่าตรงเมื่ออยู่บทเดียวกันและมีข้อซ้อนกัน */
export function popularRank(ref: string): number {
  const r = parseRef(ref)
  if (!r || !r.verses.length) return -1
  return parsed.findIndex((p) => p.book === r.book && p.chapter === r.chapter && p.verses.some((v) => r.verses.includes(v)))
}
